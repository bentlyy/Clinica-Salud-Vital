function hasSpanishWords(text) {
  const words = text.toLowerCase().split(/[\s,;:.()\[\]{}"'"`/\\@]+/).filter(Boolean);
  let spanishCount = 0;
  for (const w of words) {
    if (SPANISH_WORDS.has(w)) spanishCount++;
  }
  return spanishCount >= 2;
}

function classify(msg) {
  const lower = msg.toLowerCase();

  if (/^security/i.test(msg)) return 'security';
  if (/^(test|testing|coverage|spec(?!ial|ific))/i.test(msg)) return 'test';
  if (/^docs/i.test(msg)) return 'docs';
  if (/^chore/i.test(msg)) return 'chore';
  if (/^ci\b/i.test(msg) || /^ci\(/i.test(msg)) return 'ci';
  if (/^config/i.test(msg)) return 'config';
  if (/^refactor/i.test(msg)) return 'refactor';
  if (/^feat(\(|:)/i.test(msg) || /^feature/i.test(msg)) return 'feat';
  if (/^fix(\(|:)/i.test(msg)) return 'fix';

  if (/\b(first commit|init(ialization)?|snapshot|baseline)\b/i.test(lower)) return 'chore';
  if (/\b(buggs?|bug\b(?!ger)|error\b|solucion|resolve|crash|fail(?!over)|broken|hotfix|corregir|revert(?!\s+to)|repair|mitiga|race\s+condition|race\b|errores|corrige|restant)\b/.test(lower)) return 'fix';
  if (/\b(add(s|ed)?\b|new\b|create|implement|agregar|nuev[oa]|introduc|incorpora|mejora(s|r)?\b|improve|enhance|upgrade|rename|redesign|cambios?|actualizac|functions?\b|features?\b|nueva|mejoras|creacion)\b/.test(lower)) return 'feat';
  if (/\b(refactor|clean|simplify|remove|delete|elimin|limpiar|reorganiz|restruct|dead.?code|muertos|consolid|limpieza)\b/.test(lower)) return 'refactor';
  if (/\b(readme|\.md)\b/.test(lower)) return 'docs';
  if (/\b(package|dep|dependenc|unused|lockfile|ignore|gitignore)\b/.test(lower)) return 'chore';
  if (/\b(ci|action|workflow|deploy|build|render)\b/.test(lower)) return 'ci';
  if (/\b(security|csrf|cors|csp|helmet|hpp|audit|vulnerab|sanitiz|hardening)\b/.test(lower)) return 'security';
  if (/\b(config|configur)\b/.test(lower) && !/\b(seed|migrat)\b/.test(lower)) return 'config';

  return null;
}

function detectScope(desc, prefixScope) {
  if (prefixScope) return prefixScope;
  const lower = desc.toLowerCase();
  if (/\b(seed|migrat|schema|pool|query|rls|backfill|constraint|index|column|table|db\b|database|init\.sql)\b/.test(lower)) return 'db';
  if (/\b(security|csrf|cors|csp|helmet|audit|vulnerab|sanitiz|hardening|auth|jwt|rate.?limit)\b/.test(lower)) return 'security';
  if (/\b(docker|render|deploy|build|ci|workflow|port)\b/.test(lower)) return 'infra';
  if (/\b(test|coverage|vitest|spec|mock)\b/.test(lower)) return 'test';
  if (/\b(i18n|translat|locale|español|english|spanish|french|portugu|idioma)\b/.test(lower)) return 'i18n';
  if (/\b(frontend|ui\b|css|navbar|layout|theme|style|visual|componente|modal|card)\b/.test(lower)) return 'ui';
  if (/\b(doctor|availability|calendar|booking|specialty|panel|especialidad|disponibilidad|calendario|reserv)\b/.test(lower)) return 'doctors';
  if (/\b(analytics|ml\b|model|predic|train|forecast|demand|no.?show|analitica|análisis)\b/.test(lower)) return 'analytics';
  if (/\b(super.?admin|tenant|saas|plan|subscript|stripe|inquilino)\b/.test(lower)) return 'saas';
  if (/\b(lab|examen|resultado|technician|laboratory|exámenes)\b/.test(lower)) return 'lab';
  if (/\b(clinical|medical|ficha|historial|record|history|pacient)\b/.test(lower)) return 'clinical';
  if (/\b(email|notif|sendgrid|smtp|invit)\b/.test(lower)) return 'notifications';
  if (/\b(auth|login|logout|register|captcha|recaptcha|session|token|2fa|totp|password)\b/.test(lower)) return 'auth';
  return null;
}

function extractDescription(msg) {
  let desc = msg.replace(/^(security|test|docs|chore|ci|config|refactor|feat|fix)(\([^)]*\))?:\s*/i, '');
  return desc.trim();
}

