function capitalizeFirst(str) {
  if (!str) return str;
  return str.charAt(0).toUpperCase() + str.slice(1);
}

function transform(msg) {
  const firstLine = msg.split('\n')[0];
  const restLines = msg.split('\n').slice(1).join('\n');

  const prefixMatch = firstLine.match(/^(security|test|docs|chore|ci|config|refactor|feat|fix)(?:\(([^)]*)\))?:\s*/i);
  let desc = prefixMatch ? firstLine.slice(prefixMatch[0].length).trim() : firstLine;
  if (!desc) return msg;

  const type = classify(firstLine);
  const prefixScope = prefixMatch && prefixMatch[2] ? prefixMatch[2] : null;
  const scope = detectScope(desc, prefixScope);
  const isSpanish = hasSpanishWords(desc);

  let translated = translateEnglishToSpanish(desc);

  let result;
  if (type && scope) {
    result = `${type}(${scope}): ${capitalizeFirst(translated)}`;
  } else if (type) {
    result = `${type}: ${capitalizeFirst(translated)}`;
  } else {
    result = capitalizeFirst(translated);
  }

  if (restLines.trim()) {
    const body = restLines.trim();
    const translatedBody = translateEnglishToSpanish(body);
    result += '\n\n' + capitalizeFirst(translatedBody);
  }

  return result;
}
